local H = require("harness")
local Mock = H.Mock

describe("CharacterProvider", function()
  local ns, CP

  local function seed()
    Mock.AddItem(2589, { name = "Linen Cloth", quality = 1 })
    Mock.AddItem(2996, { name = "Bolt of Linen Cloth", quality = 1 })
    Mock.AddItem(4238, { name = "Linen Bag", quality = 1 })
    Mock.AddItem(2320, { name = "Coarse Thread", quality = 1 })
    Mock.AddRecipe({ recipeID = 2963, name = "Bolt of Linen Cloth", outputItemID = 2996, reagents = { { itemID = 2589, quantity = 2 } } })
    Mock.AddRecipe({ recipeID = 3755, name = "Linen Bag", outputItemID = 4238, reagents = { { itemID = 2996, quantity = 3 }, { itemID = 2320, quantity = 3 } } })
    Mock.OpenProfession({ professionID = 197, name = "Tailoring", skillLevel = 50, maxSkillLevel = 150, recipeIDs = { 2963, 3755 } })
    Mock.FireEvent("TRADE_SKILL_LIST_UPDATE")
    Mock.RunTimers()
    Mock.SetProfessions({ { slot = 1, name = "Tailoring", skillLevel = 50, maxSkillLevel = 150, skillLine = 197 } })
  end

  before_each(function()
    ns = H.fresh()
    H.login(ns)
    CP = ns.CharacterProvider
    seed()
  end)

  it("snapshots the current character on login and after changes", function()
    assert_not_nil(CP.Get("Thandrel-Stormhold"), "login snapshot")
    Mock.SetBag(0, 16, { { 2589, 5 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    ns.GoalService.AddCraftGoal(4238, 1)
    Mock.RunTimers()
    local record = CP.Get("Thandrel-Stormhold")
    assert_eq(record.name, "Thandrel")
    assert_eq(record.realm, "Stormhold")
    assert_eq(record.level, 60)
    assert_eq(record.classFile, "WARRIOR")
    assert_eq(record.race, "Human")
    assert_eq(record.gold, 2143600)
    assert_eq(record.bags.items[2589], 5)
    assert_nil(record.bank, "no bank visit yet")
    assert_eq(record.professions[1].name, "Tailoring")
    assert_eq(record.professions[1].skillLevel, 50)
    assert_true(record.knownRecipes[2963])
    assert_match(record.goals[1].title, "Linen Bag")
    assert_eq(record.lastSeen, Mock.now)
    local list = CP.List()
    assert_eq(#list, 1)
    assert_true(list[1].isCurrent)
    assert_eq(list[1].freshness, "live")
    assert_eq(#CP.Alts(2589), 0, "the current character is never an alt")
    assert_nil(CP.BestCoverage({ [2589] = 2 }))
    assert_true(ns.Util.IsPlainData(_G.ForeverPathDB), "snapshots must stay serializable")
    -- Bag lookups still see later changes (the snapshot must not freeze the index).
    Mock.SetBag(0, 16, { { 2589, 9 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    assert_eq(ns.InventoryProvider.GetCounts(2589).bags, 9)
  end)

  it("exposes alts' stock, crafters, coverage and freshness to another character", function()
    Mock.SetBag(0, 16, { { 2589, 8 }, { 2320, 3 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
    ns.chardb.bankCache = { items = { [2589] = 4 }, scannedAt = Mock.now }
    Mock.FireEvent("PLAYER_LOGOUT")
    local saved = Mock.deepcopy(_G.ForeverPathDB)
    assert_eq(saved.characters["Thandrel-Stormhold"].bank.items[2589], 4)

    local ns2 = H.fresh({ setup = function(M)
      M.character = { name = "Miravelle", level = 52, class = "Shaman", classFile = "SHAMAN", race = "Orc", realm = "Stormhold", money = 100 }
    end })
    _G.ForeverPathDB = saved
    H.login(ns2)
    Mock.AddItem(2589, { name = "Linen Cloth", quality = 1 })   -- the item cache is per client session
    Mock.AddItem(2996, { name = "Bolt of Linen Cloth", quality = 1 })
    local CP2 = ns2.CharacterProvider
    local list = CP2.List()
    assert_eq(#list, 2)
    assert_eq(list[1].record.name, "Miravelle")
    assert_true(list[1].isCurrent)
    assert_eq(list[2].record.name, "Thandrel")
    assert_eq(list[2].freshness, "snapshot")

    local total, alts = CP2.AltTotal(2589)
    assert_eq(total, 12)
    assert_eq(alts[1].name, "Thandrel")
    assert_eq(alts[1].bags, 8)
    assert_eq(alts[1].bank, 4)
    assert_eq(CP2.AltTotal(2589, false), 8, "bank excluded")
    assert_eq(CP2.AltTotal(9999), 0)

    local crafters = CP2.CanCraft(2996)
    assert_eq(#crafters, 1)
    assert_eq(crafters[1].name, "Thandrel")
    assert_eq(crafters[1].professionName, "Tailoring")
    assert_eq(crafters[1].skillLevel, 50)
    assert_eq(#CP2.CanCraft(2589), 0)

    local sources = CP2.Sources(2589)
    assert_eq(sources[1].kind, "alt")
    assert_eq(sources[1].name, "Thandrel")
    assert_eq(sources[1].count, 12)
    assert_match(sources[1].detail, "Thandrel has 12")
    assert_eq(CP2.Sources(2996)[1].kind, "altcraft")

    -- Inventory reports alts; the planner only counts them with includeAlts.
    local counts = ns2.InventoryProvider.GetCounts(2589)
    assert_eq(counts.alts, 12)
    assert_eq(counts.altSources[1].name, "Thandrel")
    assert_eq(counts.total, 0)
    ns2.chardb.knownRecipes[2963] = true   -- Miravelle knows the bolt recipe too
    ns2.GoalService.AddCraftGoal(2996, 2)
    local view = ns2.Planner.Evaluate(ns2.GoalService.GetSelected())
    assert_eq(view.plan.materials[1].owned, 0)
    assert_eq(view.plan.materials[1].missing, 4)
    assert_eq(view.tree.root.children[1].route, "alt")
    assert_eq(view.tree.root.children[1].hint.name, "Thandrel")
    assert_eq(view.tree.summary.missingLeaves[1].altName, "Thandrel")
    ns2.db.settings.includeAlts = true
    view = ns2.Planner.Evaluate(ns2.GoalService.GetSelected())
    assert_eq(view.plan.materials[1].owned, 12)
    assert_eq(view.plan.materials[1].missing, 0)
    assert_eq(view.plan.materials[1].ownedAlts, 12)
    assert_eq(view.tree.root.children[1].ownedAlts, 4)
    assert_eq(view.tree.root.children[1].status, "have")
    assert_match(view.inventoryNote, "Alts")

    local best = CP2.BestCoverage({ [2589] = 4, [2320] = 10 })
    assert_eq(best.name, "Thandrel")
    assert_eq(best.covered, 7)
    assert_eq(best.items[1].itemID, 2589)
    assert_eq(best.items[1].count, 4)
    assert_eq(best.items[2].count, 3)

    Mock.now = Mock.now + 3 * 86400
    assert_eq(CP2.List()[2].freshness, "cached")
    local ok, err = CP2.Remove("Miravelle-Stormhold")
    assert_false(ok)
    assert_match(err, "current")
    assert_true(CP2.Remove("Thandrel-Stormhold"))
    assert_eq(#CP2.List(), 1)
    assert_eq(CP2.AltTotal(2589), 0)
    assert_false(CP2.Remove("Thandrel-Stormhold"))
  end)

  it("captures professions late, from recorded windows, and never erases them", function()
    -- Nothing from the client list yet: fall back to professions recorded from windows.
    Mock.SetProfessions({})
    local record = CP.Snapshot()
    assert_eq(#record.professions, 1, "Tailoring was recorded when its window was open")
    assert_eq(record.professions[1].name, "Tailoring")
    assert_true(record.professions[1].scanned)
    assert_match(record.professionSource, "recorded windows only")
    -- The client list arrives later (SKILL_LINES_CHANGED) and takes over.
    Mock.SetProfessions({ { slot = 5, name = "Cooking", skillLevel = 20, maxSkillLevel = 75, skillLine = 185 }, { slot = 2, name = "Enchanting", skillLevel = 100, maxSkillLevel = 150, skillLine = 333 }, { slot = 1, name = "Tailoring", skillLevel = 60, maxSkillLevel = 150, skillLine = 197 } })
    Mock.FireEvent("SKILL_LINES_CHANGED")
    Mock.RunTimers()
    record = CP.Get("Thandrel-Stormhold")
    assert_eq(#record.professions, 3, "both primaries and the secondary")
    assert_eq(record.professions[1].name, "Tailoring", "primaries first, in slot order")
    assert_eq(record.professions[2].name, "Enchanting")
    assert_eq(record.professions[3].name, "Cooking")
    assert_eq(record.professions[1].skillLevel, 60)
    assert_nil(record.professions[1].scanned)
    assert_eq(record.professionSource, "client list")
    -- An empty client list later on (e.g. right after login) keeps the last good list.
    Mock.SetProfessions({})
    ns.chardb.professions = {}
    record = CP.Snapshot()
    assert_eq(#record.professions, 3)
    assert_match(record.professionSource, "kept")
    Mock.SetProfessions({ { slot = 5, name = "Cooking", skillLevel = 20, maxSkillLevel = 75, skillLine = 185 } })
    Mock.RunSlash("snapshot")
    assert_match(table.concat(Mock.output, " | "), "Cooking 20/75")
  end)

  it("adds up the gold you can reach across the account", function()
    H.login(ns)
    ns.db.characters["Miravelle-Stormhold"] = { key = "Miravelle-Stormhold", name = "Miravelle", realm = "Stormhold", level = 52, class = "Shaman", gold = 50000, lastSeen = Mock.now - 60, bags = { items = {} }, professions = {}, knownRecipes = {} }
    ns.db.characters["Bob-Stormhold"] = { key = "Bob-Stormhold", name = "Bob", realm = "Stormhold", level = 10, class = "Warrior", gold = 700, lastSeen = Mock.now - 60, bags = { items = {} }, professions = {}, knownRecipes = {} }
    local gold = ns.CharacterProvider.AccountGold()
    assert_eq(gold.current, 2143600)
    assert_eq(gold.altsTotal, 50700)
    assert_eq(gold.account, 2143600 + 50700)
    assert_eq(gold.alts[1].name, "Miravelle", "richest alt first")
    assert_eq(#gold.alts, 2)
  end)

end)
