local H = require("harness")
local Mock = H.Mock

describe("GoalCompletion", function()
  local ns, GC
  before_each(function()
    ns = H.fresh()
    H.login(ns)
    GC = ns.GoalCompletion
    Mock.AddItem(2589, { name = "Linen Cloth", quality = 1 })
    Mock.AddItem(2996, { name = "Bolt of Linen Cloth", quality = 1, icon = 132889 })
    Mock.AddItem(10411, { name = "Footpads of the Fang", quality = 3 })
    Mock.AddRecipe({ recipeID = 2963, name = "Bolt of Linen Cloth", outputItemID = 2996, reagents = { { itemID = 2589, quantity = 2 } } })
    Mock.OpenProfession({ professionID = 197, name = "Tailoring", skillLevel = 50, maxSkillLevel = 150, recipeIDs = { 2963 } })
    Mock.FireEvent("TRADE_SKILL_LIST_UPDATE")
    Mock.RunTimers()
  end)

  local function bags(bolts)
    Mock.SetBag(0, 16, bolts > 0 and { { 2996, bolts } } or {})
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
  end

  it("completes a crafting goal once the bags gained the quantity, and celebrates", function()
    bags(1)
    local goal = ns.GoalService.AddCraftGoal(2996, 2)
    assert_eq(goal.target.baseline, 1, "one bolt was already there")
    assert_eq(goal.target.peak, 0)
    bags(2)
    assert_eq(goal.status, "ACTIVE", "only one gained so far")
    assert_eq(goal.target.peak, 1)
    bags(3)
    assert_eq(goal.status, "COMPLETED")
    assert_eq(goal.target.completedBy, "auto")
    assert_not_nil(goal.completedAt)
    assert_output("Goal complete: Crafted 2x Bolt of Linen Cloth. 1 goal done.")
    assert_eq(Mock.sounds[1], 888, "level-up fanfare")
    local Toast = ns.UI.Toast
    local toast = Toast.frame
    assert_eq(Toast.shownCount, 1)
    assert_eq(Toast.lastShown.goalID, goal.id)
    assert_eq(toast.title:GetText(), "GOAL COMPLETE")
    assert_match(toast.name:GetText(), "Bolt of Linen Cloth")
    assert_match(toast.sub:GetText(), "^Crafted 2x Bolt of Linen Cloth  %-  1 goal done$")
    assert_false(toast:IsShown(), "the mock ran the six-second dismiss already")
    -- Using the bolts afterwards does not reopen anything.
    bags(0)
    assert_eq(goal.status, "COMPLETED")
    assert_eq(#ns.Log.errors, 0)
  end)

  it("counts the peak gain so crafted items consumed at once still complete", function()
    bags(0)
    local goal = ns.GoalService.AddCraftGoal(2996, 2)
    bags(2)
    assert_eq(goal.status, "COMPLETED")
    assert_eq(ns.UI.Toast.lastShown.goalID, goal.id)
    -- Clicking a toast opens My Goals.
    ns.UI.Toast.Show({ name = "Again", detail = "click me", goalID = goal.id })
    local toast = ns.UI.Toast.frame
    assert_true(toast:IsShown())
    toast:Click()
    assert_false(toast:IsShown())
    assert_eq(ns.UI.MainFrame.currentScreen, "goals")
  end)

  it("completes obtain goals when the quantity is on hand and respects the settings", function()
    bags(0)
    local goal = ns.GoalService.AddObtainGoal(10411, 1)
    Mock.SetBag(0, 16, { { 10411, 1 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
    assert_eq(goal.status, "COMPLETED")
    assert_output("Obtained 1x Footpads of the Fang")
    -- Switched off: nothing completes, no toast, no sound.
    ns.db.settings.autoComplete = false
    local second = ns.GoalService.AddCraftGoal(2996, 1)
    bags(1)
    assert_eq(second.status, "ACTIVE")
    ns.db.settings.autoComplete = true
    ns.db.settings.toasts = false
    ns.db.settings.completeSound = false
    Mock.sounds = {}
    ns.UI.Toast.Dismiss()
    bags(2)
    assert_eq(second.status, "COMPLETED")
    assert_eq(#Mock.sounds, 0)
    assert_eq(ns.UI.Toast.shownCount, 1, "no toast for the second completion")
  end)

  it("reopening a goal starts counting again, and old goals get a baseline first", function()
    bags(0)
    local goal = ns.GoalService.AddCraftGoal(2996, 1)
    bags(1)
    assert_eq(goal.status, "COMPLETED")
    ns.GoalService.SetStatus(goal.id, "ACTIVE")
    assert_eq(goal.target.baseline, 1, "re-based on the bolt already in the bags")
    assert_eq(goal.target.peak, 0)
    bags(1)
    assert_eq(goal.status, "ACTIVE")
    bags(2)
    assert_eq(goal.status, "COMPLETED")
    -- A goal saved by an older version has no baseline: the first check only records one.
    local old = ns.GoalService.AddCraftGoal(2996, 1)
    assert_eq(old.status, "ACTIVE")
    old.target.baseline, old.target.peak = nil, nil
    bags(5)
    assert_eq(old.status, "ACTIVE")
    assert_eq(old.target.baseline, 5)
    bags(6)
    assert_eq(old.status, "COMPLETED")
  end)

  it("queues toasts and offers a test command", function()
    local Toast = ns.UI.Toast
    Toast.Show({ name = "One", detail = "first" })
    Toast.Show({ name = "Two", detail = "second" })
    assert_match(Toast.frame.name:GetText(), "One")
    assert_true(Toast.frame:IsShown())
    assert_eq(#Toast.queue, 1)
    Mock.RunTimers(1)   -- the first toast's hold expires: the second takes its place
    assert_match(Toast.frame.name:GetText(), "Two")
    assert_true(Toast.frame:IsShown())
    assert_eq(#Toast.queue, 0)
    Mock.RunTimers()
    assert_false(Toast.frame:IsShown())
    Mock.RunSlash("celebrate test")
    assert_true(Toast.frame:IsShown())
    assert_match(Toast.frame.name:GetText(), "Linen Bag")
    Mock.RunSlash("celebrate off")
    assert_false(ns.db.settings.toasts)
    assert_false(ns.db.settings.completeSound)
    assert_output("Celebrations off")
    Mock.RunSlash("celebrate on")
    assert_true(ns.db.settings.toasts)
    Mock.RunSlash("celebrate")
    assert_output("Auto%-complete on")
  end)
end)
