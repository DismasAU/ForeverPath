local H = require("harness")

describe("Allocation ledger", function()
  local ns, Allocation
  before_each(function()
    ns = H.fresh()
    Allocation = ns.Allocation
  end)

  it("normalizes numbers, tables and garbage", function()
    assert_deep_eq(Allocation.Normalize(4), { bags = 4, bank = nil, bankSource = "none" })
    local n = Allocation.Normalize({ bags = 2, bank = 3, bankSource = "live" })
    assert_eq(n.bags, 2)
    assert_eq(n.bank, 3)
    assert_eq(n.bankSource, "live")
    assert_eq(Allocation.Normalize("x").bags, 0)
    assert_eq(Allocation.Normalize({ bank = 1 }).bankSource, "unknown")
  end)

  it("claims bags before bank and remembers what was taken", function()
    local ledger = Allocation.New()
    local counts = { bags = 3, bank = 4, bankSource = "cached" }
    local first = ledger:Take(10, counts, 5)
    assert_eq(first.total, 5)
    assert_eq(first.bags, 3)
    assert_eq(first.bank, 2)
    assert_eq(first.reserved, 0)
    assert_eq(first.availableTotal, 7)
    local second = ledger:Take(10, counts, 5)
    assert_eq(second.total, 2, "only two bank units were left")
    assert_eq(second.bags, 0)
    assert_eq(second.bank, 2)
    assert_eq(second.reserved, 5)
    assert_eq(second.availableBags, 0)
    assert_eq(second.availableBank, 2)
    assert_eq(ledger:Used(10), 7)
    local third = ledger:Take(10, counts, 1)
    assert_eq(third.total, 0)
    assert_eq(third.reserved, 7)
  end)

  it("ignores the bank when includeBank is false", function()
    local ledger = Allocation.New()
    local taken = ledger:Take(10, { bags = 1, bank = 9, bankSource = "live" }, 5, false)
    assert_eq(taken.total, 1)
    assert_eq(taken.bank, 0)
    assert_eq(ledger:Available(10, { bags = 1, bank = 9 }, false).total, 0)
  end)

  it("keeps items independent and releases claims", function()
    local ledger = Allocation.New()
    ledger:Take(10, 5, 5)
    assert_eq(ledger:Take(11, 5, 5).total, 5)
    ledger:Release(10, 2)
    assert_eq(ledger:Available(10, 5).total, 2)
    ledger:Release(10, 99)
    assert_eq(ledger:Used(10), 0)
  end)

  it("draws on alts' stock last and only when asked", function()
    local ledger = Allocation.New()
    local counts = { bags = 1, bank = 1, bankSource = "cached", alts = 5, altSources = { { name = "Miravelle", count = 5 } } }
    assert_eq(ledger:Available(10, counts, true).total, 2, "alts excluded by default")
    assert_eq(ledger:Available(10, counts, true, true).total, 7)
    local taken = ledger:Take(10, counts, 4, true, true)
    assert_eq(taken.bags, 1)
    assert_eq(taken.bank, 1)
    assert_eq(taken.alts, 2)
    assert_eq(taken.total, 4)
    assert_eq(taken.availableAlts, 5)
    assert_eq(taken.altSources[1].name, "Miravelle")
    local again = ledger:Take(10, counts, 4, true, true)
    assert_eq(again.alts, 3, "three alt units were left")
    assert_eq(again.total, 3)
    assert_eq(again.availableBags, 0)
  end)
end)
