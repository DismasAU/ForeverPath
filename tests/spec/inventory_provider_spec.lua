local H = require("harness")
local Mock = H.Mock

describe("InventoryProvider", function()
  local ns, Inv
  before_each(function()
    ns = H.fresh()
    H.login(ns)
    Inv = ns.InventoryProvider
    Mock.AddItem(2589, { name = "Linen Cloth" })
  end)

  it("counts items across bags and stacks", function()
    Mock.SetBag(0, 16, { { 2589, 20 }, { 2589, 5 } })
    Mock.SetBag(3, 6, { { 2589, 1 }, { 2996, 2 } })
    local counts = Inv.GetCounts(2589)
    assert_eq(counts.bags, 26)
    assert_eq(counts.bank, nil)
    assert_eq(counts.bankSource, "none")
    assert_eq(counts.total, 26)
    assert_eq(Inv.GetCounts(1).total, 0)
  end)

  it("rescans bags after BAG_UPDATE_DELAYED", function()
    Mock.SetBag(0, 16, { { 2589, 3 } })
    assert_eq(Inv.GetCounts(2589).bags, 3)
    Mock.SetBag(0, 16, { { 2589, 9 } })
    assert_eq(Inv.GetCounts(2589).bags, 3, "no rescan without an event")
    local fired = 0
    ns.Events.On("FP_INVENTORY_UPDATED", function() fired = fired + 1 end)
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
    assert_eq(fired, 1, "updates are debounced")
    assert_eq(Inv.GetCounts(2589).bags, 9)
  end)

  it("snapshots the bank while it is open and keeps it afterwards", function()
    Mock.SetBag(0, 16, { { 2589, 1 } })
    Mock.bankTabIDs = { 6, 7 }
    Mock.SetBag(6, 98, { { 2589, 40 } })
    Mock.SetBag(7, 98, { { 2589, 2 } })
    Mock.FireEvent("BANKFRAME_OPENED")
    Mock.RunTimers()
    local counts = Inv.GetCounts(2589)
    assert_eq(counts.bags, 1)
    assert_eq(counts.bank, 42)
    assert_eq(counts.bankSource, "live")
    assert_eq(counts.total, 43)
    Mock.SetBag(7, 98, { { 2589, 10 } })
    Mock.FireEvent("PLAYERBANKSLOTS_CHANGED")
    Mock.RunTimers()
    assert_eq(Inv.GetCounts(2589).bank, 50)
    Mock.FireEvent("BANKFRAME_CLOSED")
    Mock.RunTimers()
    counts = Inv.GetCounts(2589)
    assert_eq(counts.bankSource, "cached")
    assert_eq(counts.bank, 50)
    assert_eq(counts.bankScannedAt, Mock.now)
    assert_eq(ns.chardb.bankCache.items[2589], 50, "snapshot persists in the character database")
  end)

  it("falls back to client-reported bank counts without a snapshot", function()
    Mock.SetBag(0, 16, { { 2589, 1 } })
    Mock.bankTabIDs = { 6 }
    Mock.SetBag(6, 98, { { 2589, 7 } })
    local counts = Inv.GetCounts(2589)
    assert_eq(counts.bank, 7)
    assert_eq(counts.bankSource, "client")
    assert_eq(counts.total, 8)
  end)

  it("uses GetItemCount when container scanning is unavailable", function()
    ns = H.fresh({ setup = function() _G.C_Container = nil end })
    H.login(ns)
    Mock.SetBag(0, 16, { { 2589, 4 } })
    assert_true(ns.InventoryProvider.IsAvailable())
    assert_eq(ns.InventoryProvider.GetCounts(2589).bags, 4)
  end)

  it("reports zero when no inventory API exists", function()
    ns = H.fresh({ setup = function() _G.C_Container = nil; _G.C_Item.GetItemCount = nil end })
    H.login(ns)
    Mock.SetBag(0, 16, { { 2589, 4 } })
    assert_false(ns.InventoryProvider.IsAvailable())
    local counts = ns.InventoryProvider.GetCounts(2589)
    assert_eq(counts.bags, 0)
    assert_eq(counts.bankSource, "none")
  end)
end)
