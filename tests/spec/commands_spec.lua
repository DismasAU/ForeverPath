local H = require("harness")
local Mock = H.Mock

-- The /fp handlers no other spec runs, against a Linen Bag goal: 5 Linen
-- Cloth in the bags, a Tailoring window with both recipes recorded.
describe("Slash commands", function()
  local ns
  before_each(function()
    ns = H.fresh()
    H.login(ns)
    Mock.AddItem(2589, { name = "Linen Cloth" })
    Mock.AddItem(2996, { name = "Bolt of Linen Cloth" })
    Mock.AddItem(4238, { name = "Linen Bag" })
    Mock.AddItem(2320, { name = "Coarse Thread" })
    Mock.AddRecipe({ recipeID = 2963, name = "Bolt of Linen Cloth", outputItemID = 2996, reagents = { { itemID = 2589, quantity = 2 } } })
    Mock.AddRecipe({ recipeID = 3755, name = "Linen Bag", outputItemID = 4238, reagents = { { itemID = 2996, quantity = 3 }, { itemID = 2320, quantity = 3 } } })
    Mock.OpenProfession({ professionID = 197, name = "Tailoring", skillLevel = 50, maxSkillLevel = 150, recipeIDs = { 2963, 3755 } })
    Mock.FireEvent("TRADE_SKILL_LIST_UPDATE")
    Mock.RunTimers()
    Mock.SetBag(0, 16, { { 2589, 5 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
  end)

  it("prints the selected goal's dependency tree", function()
    Mock.RunSlash("tree")
    assert_output("No goal selected")
    ns.GoalService.AddItemGoal(4238, 1, "CRAFT_ITEM")
    Mock.RunSlash("tree")
    assert_output("Dependency tree for Craft 1x Linen Bag:")
    assert_output("Bolt of Linen Cloth x3")
    assert_output("dependencies resolved")
  end)

  it("lists characters and toggles counting alts' bags", function()
    Mock.RunSlash("characters")
    assert_output("^|cff4fc3f7ForeverPath|r: Characters %(1%):")
    assert_output("Thandrel %(you%)")
    assert_output("not counted as owned")
    assert_false(ns.GoalService.IncludesAlts())
    Mock.RunSlash("alts")
    assert_true(ns.GoalService.IncludesAlts())
    assert_output("Alts' bags and banks now count as owned.")
    Mock.RunSlash("alts")
    assert_false(ns.GoalService.IncludesAlts())
  end)

  it("describes an item's sources by id or name", function()
    Mock.RunSlash("sources")
    assert_output("Usage: /fp sources")
    Mock.RunSlash("sources linen cloth")
    assert_output("Sources for Linen Cloth:")
  end)

  it("prints the shopping list with what is still missing", function()
    ns.GoalService.AddItemGoal(4238, 1, "CRAFT_ITEM")
    Mock.RunSlash("shopping")
    assert_output("^Shopping list %(")
    assert_output("Coarse Thread")
  end)

  it("opens the window on a screen", function()
    Mock.RunSlash("open mygoals")
    assert_true(ns.UI.MainFrame.IsShown())
    assert_eq(ns.UI.MainFrame.currentScreen, "goals")
    Mock.RunSlash("open")
    assert_eq(ns.UI.MainFrame.currentScreen, "dashboard")
  end)

  it("starts a profession scan", function()
    Mock.CloseProfession()
    Mock.tradeskill.openable[197] = { professionID = 197, name = "Tailoring", recipeIDs = { 2963, 3755 } }
    Mock.SetProfessions({ { slot = 1, name = "Tailoring", skillLevel = 50, maxSkillLevel = 150, skillLine = 197 } })
    Mock.RunSlash("scan all")
    Mock.RunTimers()
    assert_deep_eq(Mock.tradeskill.openCalls, { 197 }, "scan all reopens recorded professions too")
  end)
end)
