local H = require("harness")
local Mock = H.Mock

describe("PriceProvider and the Auctionator adapter", function()
  local ns, PP
  before_each(function()
    ns = H.fresh()
    H.login(ns)
    PP = ns.PriceProvider
    Mock.AddItem(2589, { name = "Linen Cloth" })
    Mock.AddItem(2320, { name = "Coarse Thread" })
    Mock.AddItem(2996, { name = "Bolt of Linen Cloth" })
  end)

  it("reads Auctionator prices with age, average and listings", function()
    Mock.InstallAuctionator({
      [2589] = { price = 8, age = 0, mean = 9, available = 12 },
      [2320] = { price = 5, age = 3 },
    }, { lastScan = Mock.now - 4 * 3600 })
    assert_true(ns.AuctionPriceProvider.IsAvailable())
    assert_true(PP.IsAvailable())
    local cloth = PP.GetMarket(2589)
    assert_eq(cloth.copper, 8)
    assert_eq(cloth.kind, "market")
    assert_eq(cloth.source, "auctionator")
    assert_eq(cloth.avg7, 9)
    assert_eq(cloth.listings, 12)
    assert_eq(cloth.ageDays, 0)
    assert_eq(cloth.scannedAt, Mock.now - 4 * 3600, "seen today: dated by the last browse scan")
    assert_eq(PP.Freshness(cloth).key, "aging")
    assert_eq(PP.Freshness(cloth).label, "4h ago")
    local thread = PP.GetPrice(2320)
    assert_eq(thread.copper, 5)
    assert_eq(thread.scannedAt, Mock.now - 3 * 86400)
    assert_eq(PP.Freshness(thread).key, "stale")
    assert_match(PP.Freshness(thread).label, "stale")
    assert_nil(thread.avg7)
    assert_nil((PP.GetPrice(2996)))
    assert_eq(Mock.auctionatorCalls[1], 2589)
    assert_eq(PP.Freshness(nil).key, "unknown")
    assert_eq(PP.WorstFreshness(PP.Freshness(cloth), PP.Freshness(thread)).key, "stale")
    assert_eq(PP.WorstFreshness(nil, PP.Freshness(cloth)).key, "aging")
    assert_eq(PP.Freshness({ kind = "market", copper = 1 }).key, "unknown", "no scan time known")
    local status = PP.Status()
    assert_true(status.installed)
    assert_true(status.available)
    assert_eq(status.text, "AH prices: cached scan - 4h ago")
    assert_eq(status.kind, "partial")
    local lines = PP.Describe(2589)
    assert_match(lines[1], "^Auction House: 8c each %(4h ago%), 7%-day average 9c, 12 listed %- cheapest$")
  end)

  it("returns the cheapest source and keeps the others as alternatives", function()
    Mock.InstallAuctionator({ [2589] = { price = 8, age = 0 }, [2320] = { price = 50, age = 0 } })
    Mock.OpenMerchant("Tharynn Bouden", { { 2589, 5, 1 }, { 2320, 100, 1 } })
    Mock.RunTimers()
    Mock.CloseMerchant()
    local cloth = PP.GetPrice(2589)
    assert_eq(cloth.copper, 5)
    assert_eq(cloth.kind, "vendor")
    assert_eq(cloth.vendor, "Tharynn Bouden")
    assert_eq(#cloth.alternatives, 1)
    assert_eq(cloth.alternatives[1].kind, "market")
    assert_eq(cloth.alternatives[1].copper, 8)
    assert_eq(PP.Freshness(cloth).key, "vendor")
    local thread = PP.GetPrice(2320)
    assert_eq(thread.copper, 50, "the AH beats an expensive vendor")
    assert_eq(thread.kind, "market")
    assert_eq(thread.alternatives[1].kind, "vendor")
    assert_eq(PP.GetMarket(2589).copper, 8, "GetMarket ignores vendors")
    local lines = PP.Describe(2589)
    assert_match(lines[1], "^Vendor Tharynn Bouden: 5c each %- cheapest$")
    assert_match(lines[2], "^Auction House: 8c each")
    Mock.RunSlash("prices 2589")
    assert_output("Vendor Tharynn Bouden")
    Mock.RunSlash("prices")
    assert_output("AH prices: cached scan")
  end)

  it("stays quiet without Auctionator, a scan, or its database object", function()
    assert_false(ns.AuctionPriceProvider.IsAvailable())
    assert_nil((PP.GetMarket(2589)))
    local status = PP.Status()
    assert_false(status.installed)
    assert_eq(status.text, "AH prices: Auctionator not installed")
    assert_eq(status.kind, "text3")
    assert_eq(PP.Describe(2589)[1], "no price recorded (vendors are recorded when you open them; AH prices come from Auctionator scans)")
    Mock.InstallAuctionator({ [2589] = { price = 8 } }, { lastScan = false, noDatabase = true })
    status = PP.Status()
    assert_true(status.installed)
    assert_match(status.text, "no scan yet")
    local cloth = PP.GetMarket(2589)
    assert_eq(cloth.copper, 8)
    assert_nil(cloth.avg7)
    assert_nil(cloth.scannedAt)
    assert_eq(PP.Freshness(cloth).key, "unknown")
    -- An API missing its functions is "installed, unavailable".
    _G.Auctionator = { API = { v1 = {} } }
    status = PP.Status()
    assert_true(status.installed)
    assert_false(status.available)
    assert_match(status.text, "API unavailable")
    assert_nil((ns.AuctionPriceProvider.GetPrice(2589)))
    assert_eq(#ns.Log.errors, 0)
  end)
end)
