local H = require("harness")
local Mock = H.Mock

describe("VendorProvider", function()
  local ns, VP
  before_each(function()
    ns = H.fresh()
    H.login(ns)
    VP = ns.VendorProvider
    Mock.AddItem(2320, { name = "Coarse Thread" })
    Mock.AddItem(2589, { name = "Linen Cloth" })
    Mock.AddItem(159, { name = "Refreshing Spring Water" })
  end)

  it("records a merchant's stock with unit prices, zone and limits", function()
    Mock.zone, Mock.subzone = "Elwynn Forest", "Goldshire"
    Mock.OpenMerchant("Tharynn Bouden", { { 2320, 50, 5 }, { 159, 25, 1, 3 }, { 2589, 0, 1, -1, true } })
    Mock.RunTimers()
    local store = ns.db.vendors
    assert_eq(store[2320]["Tharynn Bouden"].price, 10, "50c for a stack of 5")
    assert_eq(store[2320]["Tharynn Bouden"].stack, 5)
    assert_eq(store[2320]["Tharynn Bouden"].zone, "Elwynn Forest")
    assert_eq(store[2320]["Tharynn Bouden"].subzone, "Goldshire")
    assert_false(store[2320]["Tharynn Bouden"].limited)
    assert_true(store[159]["Tharynn Bouden"].limited, "numAvailable >= 0 means limited stock")
    assert_nil(store[2589]["Tharynn Bouden"].price, "extended cost: no gold price")
    assert_true(store[2589]["Tharynn Bouden"].extended)
    assert_eq(store[2320]["Tharynn Bouden"].seenAt, Mock.now)
    assert_true(ns.Util.IsPlainData(ns.db), "vendor data must stay serializable")
    local items, vendors = VP.Count()
    assert_eq(items, 3)
    assert_eq(vendors, 1)
    Mock.CloseMerchant()
    assert_false(VP.open)
  end)

  it("exposes vendors cheapest first as hints and as a price source", function()
    Mock.OpenMerchant("Expensive Ed", { { 2320, 100, 1 } })
    Mock.CloseMerchant()
    Mock.zone = "Durotar"
    Mock.OpenMerchant("Cheap Charlie", { { 2320, 40, 5 } })
    Mock.CloseMerchant()
    local vendors = VP.VendorsFor(2320)
    assert_eq(#vendors, 2)
    assert_eq(vendors[1].name, "Cheap Charlie")
    assert_eq(vendors[1].price, 8)
    assert_eq(vendors[2].price, 100)
    local hints = VP.Sources(2320)
    assert_eq(hints[1].kind, "vendor")
    assert_eq(hints[1].name, "Cheap Charlie")
    assert_eq(hints[1].price, 8)
    assert_match(hints[1].label, "Buy from Cheap Charlie")
    assert_match(hints[1].detail, "^Durotar %- .-8c|r each$", "money text carries the coin colour code")
    local price = ns.PriceProvider.GetPrice(2320)
    assert_eq(price.copper, 8)
    assert_eq(price.kind, "vendor")
    assert_eq(price.vendor, "Cheap Charlie")
    assert_nil((ns.PriceProvider.GetPrice(2589)))
    assert_eq(#VP.Sources(2589), 0)
    assert_true(ns.PriceProvider.IsAvailable())
  end)

  it("rescans on merchant updates and ignores merchants without a name", function()
    Mock.OpenMerchant("Tharynn Bouden", { { 2320, 50, 5 } })
    Mock.merchant.items[2] = { itemID = 2589, price = 20, stack = 1 }
    Mock.FireEvent("MERCHANT_UPDATE")
    Mock.RunTimers()
    assert_eq(ns.db.vendors[2589]["Tharynn Bouden"].price, 20)
    Mock.CloseMerchant()
    Mock.merchant = { name = nil, items = { { itemID = 159, price = 5, stack = 1 } } }
    Mock.FireEvent("MERCHANT_SHOW")
    Mock.RunTimers()
    assert_nil(ns.db.vendors[159])
    Mock.FireEvent("MERCHANT_CLOSED")
  end)

  it("stays quiet when the merchant API is missing", function()
    local ns2 = H.fresh({ setup = function(M)
      M.install()
      _G.GetMerchantNumItems = nil
      _G.C_MerchantFrame = nil
    end })
    H.login(ns2)
    assert_false(ns2.VendorProvider.IsAvailable())
    Mock.merchant = { name = "X", items = {} }
    Mock.FireEvent("MERCHANT_SHOW")
    assert_eq(ns2.VendorProvider.ScanMerchant(), 0)
    assert_eq(#ns2.Log.errors, 0)
  end)
end)
