local H = require("harness")
local Mock = H.Mock

-- Enchanting (skill line 333) from the real catalogue, by spell id.
local CRUSADER, CRUSADER_FORMULA = 20034, 16252   -- Enchant Weapon - Crusader: 300, formula, 4 shards + 2 orbs
local SHARD, ORB = 14344, 12811
local MINOR_DEFLECT, LESSER_ESSENCE = 7428, 10938 -- Enchant Bracer - Minor Deflect: trainer, yellow 80, grey 120
local LINEN_BOLT, LINEN_BOLT_ITEM = 2963, 2996
local HAMMER = 21161

local CRUSADER_LINK = "|cff71d5ff|Henchant:20034|h[Enchant Weapon - Crusader]|h|r"

local function names()
  Mock.AddItem(SHARD, { name = "Large Brilliant Shard", quality = 3 })
  Mock.AddItem(ORB, { name = "Righteous Orb", quality = 2 })
  Mock.AddItem(CRUSADER_FORMULA, { name = "Formula: Enchant Weapon - Crusader", quality = 2 })
  Mock.AddItem(LESSER_ESSENCE, { name = "Lesser Magic Essence", quality = 2 })
  Mock.AddItem(LINEN_BOLT_ITEM, { name = "Bolt of Linen Cloth" })
end

local function enchanter(ns, skill, max)
  Mock.professionSlots = { 1 }
  Mock.professionInfo = { [1] = { name = "Enchanting", skillLevel = skill, maxSkillLevel = max or 300, skillLine = 333, icon = 136244 } }
  ns.chardb.professions[333] = { name = "Enchanting", skillLevel = skill, maxSkillLevel = max or 300, scannedAt = Mock.now, recipeCount = 1, learnedCount = 1 }
end

describe("Enchant goals", function()
  local ns
  before_each(function()
    ns = H.fresh()
    H.login(ns)
    names()
  end)

  it("ships enchants in the catalogue and finds them by name, kind and link", function()
    local Recipes = ns.Data.Recipes
    assert_true(Recipes.IsEnchant(CRUSADER))
    assert_false(Recipes.IsEnchant(HAMMER))
    assert_false(Recipes.IsEnchant(1))
    assert_gt(Recipes.EnchantCount(), 100)
    assert_match(Recipes.Status(), "recipes %(%d+ enchants%)")
    local recipe = Recipes.Get(CRUSADER)
    assert_eq(recipe.name, "Enchant Weapon - Crusader")
    assert_true(recipe.enchant)
    assert_nil(recipe.outputItemID)
    assert_eq(recipe.quantityMin, 1)
    assert_eq(recipe.recipeType, 3)
    assert_eq(recipe.professionName, "Enchanting")
    assert_deep_eq(recipe.skill, { min = 300, yellow = 320, green = 340, grey = 360 })
    assert_eq(recipe.teachItemID, CRUSADER_FORMULA)
    assert_eq(#recipe.reagents, 2)
    assert_true(ns.RecipeModel.Validate(recipe))
    assert_nil(Recipes.Lookup(0), "enchants are never indexed as an output item")
    assert_nil(Recipes.Get(MINOR_DEFLECT).teachItemID, "a trainer enchant")
    -- Search by kind.
    local hits = Recipes.Search("crusader", 5, nil, "enchant")
    assert_eq(hits[1].spellID, CRUSADER)
    assert_true(hits[1].enchant)
    for _, hit in ipairs(Recipes.Search("crusader", 10, nil, "item")) do
      assert_ne(hit.spellID, CRUSADER)
    end
    assert_eq(Recipes.Search("Enchant Weapon - Crusader", 5)[1].spellID, CRUSADER, "exact name first without a kind")
    -- Links and ids.
    local GS = ns.GoalService
    assert_eq(GS.SpellIDFromText(CRUSADER_LINK), CRUSADER)
    assert_eq(GS.SpellIDFromText("|cff71d5ff|Hspell:7428|h[Enchant Bracer - Minor Deflect]|h|r"), MINOR_DEFLECT)
    assert_eq(GS.SpellIDFromText("enchant:5"), 5)
    assert_eq(GS.SpellIDFromText("spell:7"), 7)
    assert_nil(GS.SpellIDFromText("Crusader"))
    assert_nil(GS.SpellIDFromText("|Hitem:2589::::|h[Linen Cloth]|h"))
    -- A scanned schematic without an item output is an enchant when the
    -- client or the catalogue says so.
    local RecipeModel = ns.RecipeModel
    local schematic = { recipeID = CRUSADER, name = "Enchant Weapon - Crusader", reagentSlotSchematics = { { reagents = { { itemID = SHARD } }, quantityRequired = 4, slotIndex = 1 } } }
    local scanned, why = RecipeModel.FromSchematic(schematic)
    assert_nil(scanned)
    assert_eq(why, "recipe has no item output")
    scanned = RecipeModel.FromSchematic(schematic, nil, { isEnchant = Recipes.IsEnchant })
    assert_true(scanned.enchant)
    assert_nil(scanned.outputItemID)
    assert_eq(scanned.quantityMax, 1)
    schematic.recipeType = 3
    schematic.recipeID = 999999
    assert_true(RecipeModel.FromSchematic(schematic).enchant, "recipeType 3 is an enchant")
    assert_false((RecipeModel.Validate({ recipeID = 1, enchant = true, outputItemID = 2, quantityMin = 1, reagents = {} })))
    -- The goal model.
    local GoalModel = ns.GoalModel
    assert_true(GoalModel.IsSupported("APPLY_ENCHANT"))
    assert_nil((GoalModel.New("APPLY_ENCHANT", { name = "x", quantity = 1 })), "spellID required")
    assert_nil((GoalModel.New("APPLY_ENCHANT", { spellID = CRUSADER })), "quantity required")
    local goal = GoalModel.New("APPLY_ENCHANT", { spellID = CRUSADER, name = "Enchant Weapon - Crusader", quantity = 2 })
    assert_eq(GoalModel.Title(goal), "Cast 2x Enchant Weapon - Crusader")
    assert_eq(GoalModel.Name(goal), "Enchant Weapon - Crusader")
    assert_true(GoalModel.SetQuantity(goal, 3))
    assert_true(GoalModel.Validate(goal))
  end)

  it("adds enchant goals from a shift-clicked link, a name or the slash command, and refuses item recipes", function()
    local GS = ns.GoalService
    local ok, message, goal = GS.AddFromInput(CRUSADER_LINK, 2)
    assert_true(ok, message)
    assert_eq(goal.type, "APPLY_ENCHANT")
    assert_eq(goal.target.spellID, CRUSADER)
    assert_eq(goal.target.quantity, 2)
    assert_eq(goal.target.casts, 0)
    assert_eq(goal.target.professionName, "Enchanting")
    assert_eq(message, "Added goal: Cast 2x Enchant Weapon - Crusader")
    assert_eq(ns.goals:GetSelectedID(), goal.id)
    -- An item recipe's link becomes a goal for the item it makes.
    local ok2, _, bolt = GS.AddFromInput("|cffffffff|Henchant:2963|h[Bolt of Linen Cloth]|h|r", 3)
    assert_true(ok2)
    assert_eq(bolt.target.itemID, LINEN_BOLT_ITEM)
    assert_eq(bolt.target.quantity, 3)
    -- Unknown spells are refused; a name finds the enchant and updates the existing goal.
    local nope, why = GS.AddFromInput("|Hspell:1|h[Nothing]|h", 1)
    assert_false(nope)
    assert_match(why, "No recipe with spell id 1")
    local ok3, message3, again = GS.AddEnchantFromInput("crusader", 1)
    assert_true(ok3, message3)
    assert_eq(again.id, goal.id)
    assert_eq(again.target.quantity, 1)
    assert_match(message3, "^Updated goal: Cast 1x Enchant Weapon %- Crusader")
    local ok4, text = GS.AddEnchantFromInput("zzzz-nothing", 1)
    assert_false(ok4)
    assert_match(text, "No enchant called")
    assert_false((GS.AddEnchantFromInput("", 1)))
    local item, reason = GS.AddEnchantGoal(HAMMER, 1)
    assert_nil(item)
    assert_match(reason, "makes an item")
    item, reason = GS.AddEnchantGoal(1, 1)
    assert_nil(item)
    assert_match(reason, "No enchant with spell id 1")
    -- /fp enchant <name> [casts]
    Mock.RunSlash("enchant minor deflect 3")
    assert_output("Added goal: Cast 3x Enchant Bracer %- Minor Deflect")
    local deflect = GS.FindEnchantGoal(MINOR_DEFLECT)
    assert_eq(deflect.target.quantity, 3)
    -- A learn-recipe goal accepts the same link.
    local ok5, _, learn = GS.AddRecipeFromInput(CRUSADER_LINK)
    assert_true(ok5)
    assert_eq(learn.type, "LEARN_RECIPE")
    assert_eq(learn.target.spellID, CRUSADER)
    assert_eq(#GS.List(), 4)
  end)

  it("plans the formula, the reagents and the casts, and completes on the player's own casts", function()
    local goal = ns.GoalService.AddEnchantGoal(CRUSADER, 2)
    -- No Enchanting at all.
    local view = ns.Planner.Evaluate(goal)
    assert_eq(view.status, ns.Status.OK)
    local e = view.enchant
    assert_eq(e.blocked, "profession")
    assert_false(e.learned)
    assert_eq(e.kind, "plans")
    assert_eq(e.remaining, 2)
    assert_eq(view.nextStep, "Learn Enchanting")
    assert_match(view.message, "^You do not have Enchanting on this character%. Get Formula: Enchant Weapon %- Crusader")
    local root = view.tree.root
    assert_eq(root.key, "enchant:" .. CRUSADER)
    assert_not_nil(root.enchant)
    assert_nil(root.itemID)
    assert_eq(root.name, "Enchant Weapon - Crusader")
    assert_false(root.claims)
    assert_eq(root.craft.crafts, 2)
    assert_true(root.craft.enchant)
    assert_false(root.craft.learned)
    assert_eq(#root.children, 3, "formula, shards, orbs")
    assert_true(root.children[1].learn)
    assert_eq(root.children[1].itemID, CRUSADER_FORMULA)
    assert_eq(root.children[2].quantity, 8)
    assert_eq(root.children[3].quantity, 4)
    assert_eq(view.tree.summary.nodes, 3)
    assert_eq(#view.plan.materials, 2)
    assert_eq(view.plan.totals.required, 12)
    assert_true(view.plan.enchant)
    assert_eq(view.plan.stepsMissing, 1)
    assert_false(view.plan.isComplete)
    assert_eq(ns.Overview.Percent(view), 0)
    assert_match(ns.DependencyResolver.Describe(view.tree, ns.ItemProvider.GetName)[1], "^Enchant Weapon %- Crusader x2 %(2 casts, not learned%)$")
    local overview = ns.Overview.Build({ { goal = goal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(overview.nextSteps[1].title, "Learn Enchanting")
    assert_eq(overview.nextSteps[1].badge, "Profession")
    assert_eq(overview.missing[1].itemID, SHARD)
    local list = ns.ShoppingList.Build({ { goal = goal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(#list.rows, 3, "the enchant itself is never on the list")
    local byItem = {}
    for _, r in ipairs(list.rows) do byItem[r.itemID] = r end
    assert_eq(byItem[CRUSADER_FORMULA].category, "learn")
    assert_eq(byItem[SHARD].missing, 8)
    assert_eq(byItem[ORB].missing, 4)
    -- An enchanter at 300 without the formula: get it, then read it.
    enchanter(ns, 300)
    view = ns.Planner.Evaluate(goal)
    assert_nil(view.enchant.blocked)
    assert_eq(view.nextStep, "Get Formula: Enchant Weapon - Crusader")
    assert_match(view.message, "^Get Formula: Enchant Weapon %- Crusader")
    Mock.SetBag(0, 16, { { CRUSADER_FORMULA, 1 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
    view = ns.Planner.Evaluate(goal)
    assert_eq(view.nextStep, "Read Formula: Enchant Weapon - Crusader")
    assert_eq(view.plan.stepsMissing, 0)
    assert_false(view.plan.isComplete, "reagents still missing")
    -- Too low a skill blocks it.
    enchanter(ns, 250)
    view = ns.Planner.Evaluate(goal)
    assert_eq(view.enchant.blocked, "skill")
    assert_eq(view.nextStep, "Reach Enchanting 300")
    assert_match(view.message, "^Needs Enchanting 300; you have 250%.")
    overview = ns.Overview.Build({ { goal = goal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(overview.nextSteps[1].title, "Reach Enchanting 300")
    -- Learned: only the reagents remain.
    enchanter(ns, 300)
    ns.chardb.knownRecipes[CRUSADER] = true
    view = ns.Planner.Evaluate(goal)
    assert_true(view.enchant.learned)
    assert_eq(#view.tree.root.children, 2)
    assert_eq(view.nextStep, "Obtain 8 x Large Brilliant Shard")
    assert_match(view.message, "^2 materials still missing for 2 casts%.$")
    overview = ns.Overview.Build({ { goal = goal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(overview.nextSteps[1].title, "Obtain 8 x Large Brilliant Shard")
    -- With the reagents: cast it.
    Mock.SetBag(0, 16, { { SHARD, 8 }, { ORB, 4 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
    assert_eq(goal.status, "ACTIVE", "bags alone never complete an enchant goal")
    view = ns.Planner.Evaluate(goal)
    assert_true(view.plan.isComplete)
    assert_eq(view.nextStep, "Cast 2 x Enchant Weapon - Crusader")
    assert_match(view.message, "^All materials for 2 casts are on hand%.$")
    assert_eq(ns.Overview.Percent(view), 100)
    overview = ns.Overview.Build({ { goal = goal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(overview.nextSteps[1].title, "Cast 2 x Enchant Weapon - Crusader")
    assert_eq(overview.nextSteps[1].badge, "Ready")
    -- Someone else's cast does not count; the player's does.
    Mock.CastSpell(CRUSADER, "target")
    assert_eq(goal.target.casts, 0)
    Mock.CastSpell(MINOR_DEFLECT)
    assert_eq(goal.target.casts, 0)
    Mock.CastSpell(CRUSADER)
    assert_eq(goal.target.casts, 1)
    assert_eq(goal.status, "ACTIVE")
    view = ns.Planner.Evaluate(goal)
    assert_eq(view.enchant.casts, 1)
    assert_eq(view.enchant.remaining, 1)
    assert_eq(view.plan.craftsNeeded, 1)
    assert_eq(view.plan.totals.required, 6)
    assert_eq(view.tree.root.quantity, 1)
    assert_match(view.message, "^1 of 2 casts done%. All materials for 1 cast are on hand%.$")
    assert_match(ns.DependencyResolver.Describe(view.tree, ns.ItemProvider.GetName)[1], "^Enchant Weapon %- Crusader x1 %(1 cast%)$")
    Mock.CastSpell(CRUSADER)
    assert_eq(goal.status, "COMPLETED")
    assert_eq(goal.target.completedBy, "auto")
    assert_output("Goal complete: Cast 2x Enchant Weapon %- Crusader%.")
    assert_eq(ns.UI.Toast.lastShown.title, "Enchant applied")
    view = ns.Planner.Evaluate(goal)
    assert_true(view.plan.isComplete)
    assert_eq(view.enchant.remaining, 0)
    assert_eq(view.message, "Enchant Weapon - Crusader cast 2 times.")
    assert_eq(view.nextStep, "Mark the goal complete")
    assert_eq(ns.Overview.Percent(view), 100)
    overview = ns.Overview.Build({ { goal = goal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(#overview.nextSteps, 0, "completed goals are not active")
    -- Reopening starts the count over.
    ns.GoalService.SetStatus(goal.id, "ACTIVE")
    assert_eq(goal.target.casts, 0)
    assert_eq(ns.Planner.Evaluate(goal).enchant.remaining, 2)
  end)

  it("plans a trainer enchant as a train step and crafts enchants for Enchanting skill goals", function()
    enchanter(ns, 100)
    local goal = ns.GoalService.AddEnchantGoal(MINOR_DEFLECT, 1)
    local view = ns.Planner.Evaluate(goal)
    assert_eq(view.enchant.kind, "trainer")
    assert_eq(view.nextStep, "Visit an Enchanting trainer")
    assert_match(view.message, "^Train at any Enchanting trainer")
    local root = view.tree.root
    assert_eq(#root.children, 2, "train step and the essence")
    assert_not_nil(root.children[1].step)
    assert_eq(root.children[1].step.kind, "train")
    assert_eq(root.children[1].step.spellID, MINOR_DEFLECT)
    assert_eq(root.children[2].itemID, LESSER_ESSENCE)
    assert_eq(view.plan.stepsMissing, 1)
    local list = ns.ShoppingList.Build({ { goal = goal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(#list.rows, 2)
    local keys = {}
    for _, r in ipairs(list.rows) do keys[r.key] = r.category end
    assert_eq(keys["train:" .. MINOR_DEFLECT], "learn")
    assert_eq(keys[LESSER_ESSENCE], "buy")
    -- A recorded trainer names itself.
    Mock.zone = "Stormwind City"
    Mock.OpenTrainer("Lucan Cordell", { { spellID = MINOR_DEFLECT, name = "Enchant Bracer - Minor Deflect", type = "available", skill = "Enchanting", rank = 80, cost = 1500 } })
    Mock.RunTimers()
    Mock.CloseTrainer()
    view = ns.Planner.Evaluate(goal)
    assert_eq(view.enchant.trainer.name, "Lucan Cordell")
    assert_eq(view.nextStep, "Train at Lucan Cordell")
    assert_match(view.message, "^Train at Lucan Cordell, Stormwind City for 15s 0c%.")
    -- Learned, with the essence in the bags: the crafting screen shows it as a cast.
    ns.chardb.knownRecipes[MINOR_DEFLECT] = true
    Mock.SetBag(0, 16, { { LESSER_ESSENCE, 5 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
    view = ns.Planner.Evaluate(goal)
    assert_true(view.plan.isComplete)
    assert_eq(#view.tree.root.children, 1)
    local MainFrame = ns.UI.MainFrame
    MainFrame.Show()
    Mock.RunTimers()
    MainFrame.OpenGoal(goal.id)
    Mock.RunTimers()
    assert_eq(MainFrame.currentScreen, "crafting")
    local crafting = MainFrame.screens.crafting
    assert_match(crafting.hero.name:GetText(), "Enchant Bracer %- Minor Deflect")
    assert_eq(crafting.hero.meta:GetText(), "Enchanting enchant - needs 80 - taught by a trainer")
    assert_eq(crafting.hero.chips[1].label:GetText(), "Known")
    assert_eq(crafting.hero.chips[2].label:GetText(), "0 of 1 cast")
    assert_match(crafting.hero.reagents:GetText(), "^1 of 1 reagents in your bags %- 1 cast to do")
    assert_match(crafting.pool.rows[1].name:GetText(), "Lesser Magic Essence")
    crafting.tab = "tree"
    crafting:Refresh()
    local treeRow = crafting.treeView.pool.rows[1]
    assert_match(treeRow.name:GetText(), "Enchant Bracer %- Minor Deflect")
    assert_eq(treeRow.note:GetText(), "1 cast")
    assert_eq(treeRow.via:GetText(), "Cast - Enchanting")
    crafting.tab = "requirements"
    MainFrame.ShowScreen("goals")
    Mock.RunTimers()
    local goalRow = MainFrame.screens.goals.rowPool.rows[1]
    assert_match(goalRow.sub:GetText(), "^0 of 1 cast %- Cast 1 x Enchant Bracer %- Minor Deflect")
    assert_eq(goalRow.badge.label:GetText(), "ENCHANT")
    MainFrame.Hide()
    -- An Enchanting skill goal plans the enchants you know, reagents only.
    ns.GoalService.Remove(goal.id)
    local ok, message, skillGoal = ns.GoalService.AddSkillFromInput("enchanting 110")
    assert_true(ok, message)
    view = ns.Planner.Evaluate(skillGoal)
    assert_eq(view.skillPlan.list[1].spellID, MINOR_DEFLECT)
    local craft = view.tree.root.children[1]
    assert_nil(craft.itemID)
    assert_eq(craft.name, "Enchant Bracer - Minor Deflect")
    assert_not_nil(craft.forSkill)
    assert_eq(view.plan.materials[1].itemID, LESSER_ESSENCE)
    assert_match(ns.DependencyResolver.Describe(view.tree, ns.ItemProvider.GetName)[2], "^  Enchant Bracer %- Minor Deflect x%d+ for skill 100%-110")
    local overview = ns.Overview.Build({ { goal = skillGoal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_match(overview.nextSteps[1].title, "^Obtain %d+ x Lesser Magic Essence$")
    Mock.SetBag(0, 16, { { LESSER_ESSENCE, 200 } })
    Mock.FireEvent("BAG_UPDATE_DELAYED")
    Mock.RunTimers()
    view = ns.Planner.Evaluate(skillGoal)
    overview = ns.Overview.Build({ { goal = skillGoal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_match(overview.nextSteps[1].title, "^Cast %d+ x Enchant Bracer %- Minor Deflect$")
    local list2 = ns.ShoppingList.Build({ { goal = skillGoal, view = view } }, { nameOf = ns.ItemProvider.GetName })
    assert_eq(#list2.rows, 0, "everything in the bags")
  end)
end)
