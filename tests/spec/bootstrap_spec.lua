local H = require("harness")
local Mock = H.Mock

describe("Bootstrap and slash commands", function()
  local ns
  before_each(function()
    ns = H.fresh()
  end)

  it("initialises on ADDON_LOADED", function()
    assert_false(ns.loaded)
    local ready = false
    ns.Events.On("FP_READY", function() ready = true end)
    H.login(ns)
    assert_true(ns.loaded)
    assert_true(ready)
    assert_not_nil(ns.db)
    assert_not_nil(ns.chardb)
    assert_eq(ns.VERSION, "0.1.0-test", "version read from TOC metadata")
    assert_not_nil(ns.goals)
    assert_true(ns.Compat.client.isForever)
    assert_eq(ns.Compat.client.interface, 16001)
  end)

  it("still loads when one module's Init raises", function()
    ns.QuestieBridge.Init = function() error("bridge exploded") end
    local ready = false
    ns.Events.On("FP_READY", function() ready = true end)
    H.login(ns)
    assert_true(ns.loaded, "the rest of the addon loads")
    assert_true(ready)
    assert_not_nil(ns.goals, "modules after the failing one still start")
    assert_match(ns.Log.errors[1].message, "bridge exploded")
  end)

  it("names every module in the Init order", function()
    for _, path in ipairs(ns.Bootstrap.INIT_ORDER) do
      local module = ns
      for part in path:gmatch("[^.]+") do module = module[part] end
      assert_eq(type(module.Init), "function", path .. ".Init")
    end
  end)

  it("lists every message the addon fires or listens to", function()
    local known = {}
    for _, name in ipairs(ns.Events.MESSAGES) do known[name] = true end
    for _, rel in ipairs(H.tocFiles(H.root .. "/ForeverPath/ForeverPath.toc")) do
      local source = H.readFile(H.root .. "/ForeverPath/" .. rel)
      for name in source:gmatch('"(FP_[A-Z_]+)"') do
        assert_true(known[name], name .. " (" .. rel .. ") is not in Events.MESSAGES")
      end
    end
  end)

  it("ignores other addons' ADDON_LOADED", function()
    Mock.FireEvent("ADDON_LOADED", "SomethingElse")
    assert_false(ns.loaded)
  end)

  it("survives registering an event the client does not know", function()
    local ok = ns.Events.RegisterWoW("FP_NOT_A_REAL_EVENT", function() end)
    assert_false(ok)
    assert_eq(#ns.Log.errors, 0)
  end)

  it("captures handler errors instead of crashing", function()
    ns.Events.On("FP_TEST", function() error("kaboom") end)
    ns.Events.Fire("FP_TEST")
    assert_eq(#ns.Log.errors, 1)
    assert_match(ns.Log.errors[1].message, "kaboom")
    assert_output("ForeverPath error")
  end)

  it("Log.Try passes every result through and logs a raise instead of hiding it", function()
    local a, b, c = ns.Log.Try(function(x) return x, 2, 3 end, 1)
    assert_eq(a, 1)
    assert_eq(c, 3)
    assert_nil(ns.Log.Try(nil))
    assert_eq(#ns.Log.errors, 0)
    assert_nil(ns.Log.Try(function() error("source broke") end))
    assert_eq(#ns.Log.errors, 1)
    assert_match(ns.Log.errors[1].message, "source broke")
  end)

  it("refuses data commands before loading", function()
    Mock.RunSlash("add 2996")
    assert_output("Still loading")
  end)

  it("toggles the window with /fp", function()
    H.login(ns)
    Mock.RunSlash("")
    assert_true(ns.UI.MainFrame.IsShown())
    assert_not_nil(_G.ForeverPathMainFrame)
    Mock.RunSlash("")
    assert_false(ns.UI.MainFrame.IsShown())
    _G.ForeverPath_OnAddonCompartmentClick()
    assert_true(ns.UI.MainFrame.IsShown())
  end)

  it("prints help and handles unknown commands", function()
    Mock.RunSlash("help")
    assert_output("/fp add")
    Mock.RunSlash("bogus")
    assert_output("Unknown command")
  end)

  it("toggles debug logging persistently", function()
    H.login(ns)
    assert_false(ns.Log.debugEnabled)
    Mock.RunSlash("debug")
    assert_true(ns.Log.debugEnabled)
    assert_true(ns.db.settings.debug)
    Mock.RunSlash("debug")
    assert_false(ns.db.settings.debug)
  end)

  it("adds, lists, selects and removes goals from chat", function()
    H.login(ns)
    Mock.AddItem(2996, { name = "Bolt of Linen Cloth" })
    Mock.AddItem(2589, { name = "Linen Cloth" })
    Mock.RunSlash("add 2996 3")
    assert_output("Added goal: Craft 3x Bolt of Linen Cloth")
    Mock.RunSlash("add " .. Mock.ItemLink(2589))
    assert_output("Added goal: Obtain 1x Linen Cloth", "the catalogue knows no recipe makes Linen Cloth")
    assert_eq(#ns.GoalService.List(), 2)
    Mock.RunSlash("add 2996 5")
    assert_output("Updated goal: Craft 5x Bolt of Linen Cloth")
    assert_eq(#ns.GoalService.List(), 2)
    Mock.RunSlash("goals")
    assert_output("%*1%. Craft 5x Bolt of Linen Cloth", "updating a goal selects it")
    assert_output("   2%. Obtain 1x Linen Cloth")
    Mock.RunSlash("select 2")
    assert_eq(ns.GoalService.GetSelected().target.itemID, 2589)
    Mock.RunSlash("select 1")
    assert_eq(ns.GoalService.GetSelected().target.itemID, 2996)
    Mock.RunSlash("remove 1")
    assert_eq(#ns.GoalService.List(), 1)
    Mock.RunSlash("remove 9")
    assert_output("No such goal")
    Mock.RunSlash("add 123456")
    assert_output("does not exist")
    Mock.RunSlash("add Nothing Like This")
    assert_output("No item named")
    Mock.RunSlash("obtain 2589 4")
    assert_output("Updated goal: Obtain 4x Linen Cloth", "/fp obtain switches the existing goal's type")
    assert_eq(ns.GoalService.List()[1].type, "OBTAIN_ITEM")
    Mock.RunSlash("obtain 2996")
    assert_output("Added goal: Obtain 1x Bolt of Linen Cloth")
  end)

  it("keeps goals across a reload", function()
    H.login(ns)
    Mock.AddItem(2996, { name = "Bolt" })
    Mock.RunSlash("add 2996 2")
    local saved = Mock.deepcopy(_G.ForeverPathCharDB)
    assert_true(ns.Util.IsPlainData(_G.ForeverPathCharDB))
    local ns2 = H.fresh()
    _G.ForeverPathCharDB = saved
    H.login(ns2)
    local goals = ns2.GoalService.List()
    assert_eq(#goals, 1)
    assert_eq(goals[1].target.quantity, 2)
    assert_eq(ns2.GoalService.GetSelected().id, goals[1].id)
  end)

  it("answers status and errors without raising", function()
    H.login(ns)
    Mock.RunSlash("status")
    assert_output("Forever client: yes")
    assert_output("Recorded professions: none")
    assert_output("^  Attune: not installed")
    assert_output("^  Item sources: AtlasLoot ")
    assert_output("^  AH prices: ")
    Mock.RunSlash("errors")
    assert_output("No errors recorded")
    Mock.RunSlash("reset window")
    assert_output("reset")
    assert_eq(#ns.Log.errors, 0)
  end)
end)
